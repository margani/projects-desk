// Local build: status/*.json and usage/*.json on disk → dist/index.html, for
// `npm run dev` and the tests. Production renders the same page in the Worker
// from D1; for it, the build only writes the app files and
// dist/inline.mjs (the CSS and client script the Worker inlines).
// Invalid files never fail the build: they render as warning cards.
import { readFile, readdir, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { renderSite, parseUsage, checkGithubUsage, checkStorage, checkApps, checkClaude, checkUsers } from './lib/site.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export async function build({ statusDir = path.join(root, 'status'), usageFile = path.join(root, 'usage/github.json'), storageFile = path.join(root, 'usage/storage.json'), appsFile = path.join(root, 'usage/apps.json'), claudeFile = path.join(root, 'usage/claude.json'), usersFile = path.join(root, 'usage/users.json'), outDir = path.join(root, 'dist'), now = Date.now(), log = console.log } = {}) {
  const [css, js] = await Promise.all([
    readFile(path.join(root, 'src/styles.css'), 'utf8'),
    readFile(path.join(root, 'src/client.js'), 'utf8'),
  ]);
  await mkdir(outDir, { recursive: true });
  await writeAppFiles(outDir);
  await writeFile(path.join(outDir, 'inline.mjs'), `// Generated by scripts/build.mjs for src/worker.mjs.\nexport const css = ${JSON.stringify(css)};\nexport const js = ${JSON.stringify(js)};\n`);
  // Never served as files: the Worker answers / and /version.json from D1.
  await writeFile(path.join(outDir, '.assetsignore'), 'index.html\nversion.json\ninline.mjs\n');

  let files;
  try {
    files = (await readdir(statusDir)).filter((f) => f.endsWith('.json')).sort();
  } catch {
    // Workers Builds: status files live in D1, not in the repository.
    log('No status/ folder: built the app files and dist/inline.mjs only.');
    return { entries: [], version: null };
  }
  const statusRows = await Promise.all(files.map(async (file) => {
    const name = file.slice(0, -'.json'.length);
    try {
      return { name, text: await readFile(path.join(statusDir, file), 'utf8') };
    } catch (err) {
      return { name, problem: `Could not read file: ${err.message}` };
    }
  }));
  const usage = parseUsage(await readFile(usageFile, 'utf8').catch(() => null), checkGithubUsage, 'GitHub usage file', log);
  const storage = parseUsage(await readFile(storageFile, 'utf8').catch(() => null), checkStorage, 'storage usage file', log);
  const apps = parseUsage(await readFile(appsFile, 'utf8').catch(() => null), checkApps, 'desktop apps file', log);
  const claude = parseUsage(await readFile(claudeFile, 'utf8').catch(() => null), checkClaude, 'Claude usage file', log);
  const users = parseUsage(await readFile(usersFile, 'utf8').catch(() => null), checkUsers, 'user numbers file', log);
  const { entries, version, html } = await renderSite({ statusRows, usage, storage, apps, claude, users, css, js, now });

  for (const x of entries) {
    if (x.ok) log(`  ok       ${x.name}`);
    else log(`  INVALID  ${x.name}: ${x.problems.join(' | ')}`);
  }
  await writeFile(path.join(outDir, 'index.html'), html);
  // Open pages poll this file and offer a reload when it changes.
  await writeFile(path.join(outDir, 'version.json'), JSON.stringify({ version }) + '\n');
  log(`Built ${path.relative(root, path.join(outDir, 'index.html'))} from ${entries.length} status file(s), ${entries.filter((x) => !x.ok).length} invalid.`);
  return { entries, version };
}

/** What makes the page an installable app: manifest, icons, service worker. */
async function writeAppFiles(outDir) {
  await mkdir(path.join(outDir, 'icons'), { recursive: true });
  for (const name of ['icon-180', 'icon-192', 'icon-512', 'icon-maskable-512']) {
    await copyFile(path.join(root, `src/icons/${name}.png`), path.join(outDir, `icons/${name}.png`));
  }
  await copyFile(path.join(root, 'src/sw.js'), path.join(outDir, 'sw.js'));
  const manifest = {
    name: 'Projects',
    short_name: 'Projects',
    description: 'Status of all my projects',
    id: './',
    start_url: './',
    scope: './',
    // Lets the desktop app hide its title bar; the page keeps a
    // draggable strip where it was. Browsers without it fall back to standalone.
    display_override: ['window-controls-overlay'],
    display: 'standalone',
    // The installed Android app paints its navigation bar from these, and the
    // manifest has no dark variant: light values left a white bar under the
    // dark page. A dark theme_color alone did not help; on the owner's
    // phone the bar matched background_color exactly. Dark is the scheme the
    // app is used in; the status bar still follows the theme-color meta tags.
    background_color: '#121417',
    theme_color: '#121417',
    // `any` icons are a rounded card on transparency, because desktop docks
    // show them as they are; a full square looked out of place. Android
    // crops the full-bleed maskable one itself.
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  };
  await writeFile(path.join(outDir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await build();
}
